source("pre.R"); library(vctrs)
L <- list(i64=i64e,u64=u64e,i128=i128e,u128=u128e)
for (n in names(L)) { x <- L[[n]]; ch <- as.character(x)
  chk <- function(lab, got, want) if (!identical(got, want)) { cat("DIFF", n, lab, "\n got: "); print(got); cat(" want: "); print(want) }
  chk("slice", as.character(vec_slice(x, c(2L,NA,1L))), ch[c(2,NA,1)])
  chk("class", class(vec_slice(x, 1:2)), class(x))
  chk("init", as.character(vec_init(x, 3)), rep(NA_character_,3))
  chk("isna init", is.na(vec_init(x,3)), rep(TRUE,3))
  chk("vec_c", as.character(vec_c(x, x[0], NA, x)), c(ch, NA, ch))
  chk("detect_missing", vec_detect_missing(x), is.na(ch))
  chk("equal", vec_equal(x, rev(x)), ch == rev(ch))
  chk("equal na", vec_equal(x, rev(x), na_equal=TRUE), ifelse(is.na(ch)|is.na(rev(ch)), is.na(ch)&is.na(rev(ch)), ch==rev(ch)))
  chk("unique", as.character(vec_unique(c(x,x))), unique(c(ch,ch)))
  chk("match", vec_match(x, rev(x)), match(ch, rev(ch)))
  chk("in", vec_in(x, x[2:3]), ch %in% ch[2:3])
  chk("group_id", as.integer(vec_group_id(c(x,rev(x)))), match(c(ch,rev(ch)), unique(c(ch,rev(ch)))))
  # order by gmp
  g <- gmp::as.bigz(ch[!is.na(ch)]); 
  perm <- sample(length(x)); xs <- x[perm]
  o <- vec_order(xs); want <- c(ch[!is.na(ch)][order(g)], NA)
  chk("order", as.character(xs[o]), want)
  chk("sort", as.character(vec_sort(xs)), c(ch[!is.na(ch)][order(g)],NA))
  chk("sort desc", as.character(vec_sort(xs, direction="desc")), c(NA,rev(ch[!is.na(ch)][order(g)])))
  chk("rank", vec_rank(xs, incomplete="na"), { r<-rep(NA_integer_, length(xs)); r[!is.na(xs)] <- rank(gmp::as.bigz(as.character(xs[!is.na(xs)]))); as.integer(r)})
  chk("compare", vec_compare(x, rev(x)), { a<-gmp::as.bigz(ch); b<-gmp::as.bigz(rev(ch)); {r<-as.integer(sign(a-b)); r[is.na(ch)|is.na(rev(ch))]<-NA; r}})
  chk("count", vec_count(c(x,x[1:3]), sort="location")$count, as.integer(table(factor(c(ch,ch[1:3]), levels=unique(ch), exclude=NULL))))
  chk("assign", as.character(vec_assign(x, 2:3, x[1])), {c2<-ch; c2[2:3]<-ch[1]; c2})
  chk("assign NA", as.character(vec_assign(x, 2:3, NA)), {c2<-ch; c2[2:3]<-NA; c2})
  chk("recycle", as.character(vec_recycle(x[2], 3)), rep(ch[2],3))
  chk("rep", as.character(vec_rep_each(x, 2)), rep(ch, each=2))
  sp <- vec_split(seq_along(c(x,x)), c(x,x)); chk("split key", as.character(sp$key), ch); chk("split val", sp$val, lapply(seq_along(x), function(i) c(i, i+length(x))))
  chk("chop/unchop", as.character(list_unchop(vec_chop(x))), ch)
  chk("unchop idx", as.character(list_unchop(list(x[1:2], x[3]), indices=list(c(1,3), 2), ptype=x)), c(ch[1], ch[3], ch[2]))
  chk("if_else", as.character(tryCatch(vctrs::vec_if_else(c(TRUE,FALSE,NA), x[1:3], x[3:1]), error=function(e) dplyr::if_else(c(TRUE,FALSE,NA), x[1:3], x[3:1]))), c(ch[1], ch[2], NA))
  lm <- vec_locate_matches(x, rev(x)); chk("locate", lm$haystack, match(ch, rev(ch)))
  lm <- vec_locate_matches(x, x[0]); chk("locate none", as.character(vec_slice(x, lm$haystack)), rep(NA_character_, length(x)))
  d <- vec_rbind(tibble::tibble(a=1), tibble::tibble(a=2, b=x[2])); chk("rbind pad", as.character(d$b), c(NA, ch[2])); chk("rbind pad isna", is.na(d$b), c(TRUE,FALSE))
  chk("duplicated", vec_duplicate_detect(c(x,x[2])), ch %in% ch[2] |> c(TRUE))
  chk("names kept?", names(vec_slice(setNames(x, letters[seq_along(x)]), 1:2)), c("a","b"))
  chk("fill", as.character(vec_fill_missing(c(x[8], x[2], x[8], x[3], x[8]))), c(NA, ch[2], ch[2], ch[3], ch[3]))
  chk("run", vec_identify_runs(c(x[2],x[2],x[3],x[3]))[1:4], c(1L,1L,2L,2L))
  chk("ser", identical(unserialize(serialize(x, NULL)), x), TRUE)
}
