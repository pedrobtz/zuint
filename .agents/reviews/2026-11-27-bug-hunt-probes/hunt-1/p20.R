cat(sprintf("mean %.17g  true %.17g  rel.err %.3g  ulps %.0f\n", m, true, (m - true) / true, (m - true) / (2^(floor(log2(true)) - 52))))
cat(sprintf("as.double(sum(x))/n: %.17g\n", as.double(sum(x)) / length(x)))
