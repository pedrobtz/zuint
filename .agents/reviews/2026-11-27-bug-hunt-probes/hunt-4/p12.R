source("helper.R")
rel <- function() .Call(zuint:::zu_arrow_releases_c)
x <- int128(c("1", NA, "-170141183460469231731687303715884105727"))
cat("== raw from handler\n")
a <- zuint:::zu_arrow_from(x); print(class(a)); s <- zuint:::zu_arrow_tag(a); print(class(s))
print(nanoarrow_schema_parse(s)[c("type","extension_name")]); print(s$flags); print(s$name); str(s$metadata)
h <- zuint:::zu_arrow_to(NA_integer_)
r1 <- h(a, s, "error"); r2 <- h(a, s, "error"); cat("import twice identical:", identical(r1, x), identical(r2, x), "\n")
b0 <- rel(); cat("release ->", .Call(zuint:::zu_arrow_release_c, a), "again ->", .Call(zuint:::zu_arrow_release_c, a), "count delta", rel() - b0, "\n")
cat("released?", .Call(zuint:::zu_arrow_released_c, a), "\n")
r <- tryCatch(h(a, s, "error"), error = function(e) paste(class(e)[1], conditionMessage(e))); print(r)
r <- tryCatch(zuarrow::arrow_to_r(a), error = function(e) paste(class(e)[1], conditionMessage(e))); print(r)
b0 <- rel(); rm(a, s); invisible(gc()); invisible(gc()); cat("gc after manual release: delta", rel() - b0, "\n")
cat("== gc of live export\n")
b0 <- rel(); a <- zuint:::zu_arrow_from(x); rm(a); invisible(gc()); invisible(gc()); cat("delta", rel() - b0, "\n")
cat("== schema outlives array handle?\n")
a <- zuint:::zu_arrow_from(uint128(c("5", NA))); s <- zuint:::zu_arrow_tag(a); rm(a); invisible(gc()); invisible(gc())
print(tryCatch(nanoarrow_schema_parse(s)$extension_name, error = function(e) conditionMessage(e)))
cat("== move out via nanoarrow (nanoarrow_pointer_move / export)\n")
b0 <- rel(); a <- zuint:::zu_arrow_from(x); s <- zuint:::zu_arrow_tag(a)
dst <- nanoarrow_allocate_array(); nanoarrow_pointer_move(a, dst)
cat("src released flag after move:", .Call(zuint:::zu_arrow_released_c, a), "\n")
print(tryCatch(h(a, s, "error"), error = function(e) paste(class(e)[1], conditionMessage(e))))
rm(a); invisible(gc()); invisible(gc()); cat("delta after gc of moved-from src:", rel() - b0, "\n")
nanoarrow_array_set_schema(dst, s, validate = FALSE)
r <- zuarrow::arrow_to_r(dst); cat("moved array still readable:", identical(r, x), "\n")
rm(dst, r); invisible(gc()); invisible(gc()); cat("delta after gc of moved dst:", rel() - b0, "\n")
cat("== through zuarrow::arrow_array + arrow_release\n")
b0 <- rel(); za <- zuarrow::arrow_array(x); print(class(za)); 
r <- zuarrow::arrow_to_r(za); r <- zuarrow::arrow_to_r(za); cat("twice ok", identical(r, x), "\n")
zuarrow::arrow_release(za); cat("delta after arrow_release:", rel() - b0, "\n")
print(tryCatch(zuarrow::arrow_to_r(za), error = function(e) paste(class(e)[1], conditionMessage(e))))
print(tryCatch({zuarrow::arrow_release(za); "second release ok"}, error = function(e) paste(class(e)[1], conditionMessage(e))))
rm(za); invisible(gc()); cat("delta after gc:", rel() - b0, "\n")
cat("== stream export, many\n")
b0 <- rel(); for (i in 1:200) { df <- data.frame(a = int64(1:10)); df$b <- uint128(1:10); raw <- zuarrow::arrow_write(df, NULL, format = "stream") }; invisible(gc()); invisible(gc()); cat("delta (expect 400):", rel() - b0, "\n")
cat("== handler: schema not the array's own\n")
a <- zuint:::zu_arrow_from(int64(1:3)); s128 <- zuint:::zu_arrow_tag(zuint:::zu_arrow_from(int128(1)))
print(tryCatch(h(a, s128, "error"), error = function(e) paste(class(e)[1], conditionMessage(e))))
# same format, different extension: uhugeint schema with hugeint array
ah <- zuint:::zu_arrow_from(int128(-1)); su <- zuint:::zu_arrow_tag(zuint:::zu_arrow_from(uint128(1)))
print(tryCatch(format(h(ah, su, "allow")), error = function(e) paste(class(e)[1], conditionMessage(e))))
cat("== corrupt\n")
for (k in 1:4) { a <- zuint:::zu_arrow_from(int64(1:3)); .Call(zuint:::zu_arrow_corrupt_c, a, k); print(tryCatch(h(a, zuint:::zu_arrow_tag(a), "error"), error = function(e) paste(class(e)[1], conditionMessage(e)))) }
cat("== non-pointer args\n")
print(tryCatch(h(1, 2, "error"), error = function(e) paste(class(e)[1], conditionMessage(e))))
print(tryCatch(zuint:::zu_arrow_from(1:3), error = function(e) paste(class(e)[1], conditionMessage(e))))
print(tryCatch(zuint:::zu_arrow_from(structure(1:3, class = "zu_int64")), error = function(e) paste(class(e)[1], conditionMessage(e))))
print(tryCatch(zuint:::zu_arrow_from(structure(c(1,2), class = "zu_int128")), error = function(e) paste(class(e)[1], conditionMessage(e))))
